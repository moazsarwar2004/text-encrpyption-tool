const input = document.querySelector('#input');
const method = document.querySelector('#method');
const keyWrap = document.querySelector('#keyWrap');
const key = document.querySelector('#key');
const keyLabel = document.querySelector('#keyLabel');
const keyHint = document.querySelector('#keyHint');
const output = document.querySelector('#output');
const error = document.querySelector('#error');
const status = document.querySelector('#status');

method.addEventListener('change', () => {
  keyWrap.hidden = !method.value;
  key.value = '';
  output.value = '';
  error.textContent = '';
  status.textContent = '';
  if (method.value === 'caesar') {
    keyLabel.textContent = 'Shift (1–25)';
    keyHint.textContent = 'Example: 3 shifts A to D.';
    key.type = 'number'; key.min = '1'; key.max = '25'; key.step = '1';
  } else if (method.value === 'vigenere') {
    keyLabel.textContent = 'Keyword';
    keyHint.textContent = 'Letters A–Z only; the same keyword is needed to decrypt.';
    key.type = 'text';
  } else if (method.value === 'aes') {
    keyLabel.textContent = 'Password';
    keyHint.textContent = 'Keep this password: it is required to decrypt the result.';
    key.type = 'password';
  }
});

function validate() {
  if (!input.value.trim()) throw new Error('Enter some text first.');
  if (!method.value) throw new Error('Select an encryption method.');
  if (method.value === 'caesar' && (!/^\d+$/.test(key.value) || Number(key.value) < 1 || Number(key.value) > 25)) {
    throw new Error('Enter a whole-number shift from 1 to 25.');
  }
  if (method.value === 'vigenere' && !/^[A-Za-z]+$/.test(key.value)) {
    throw new Error('Enter a keyword containing letters A–Z only.');
  }
  if (method.value === 'aes' && !key.value) throw new Error('Enter a password.');
}

function shiftLetter(char, amount) {
  const code = char.charCodeAt(0);
  const base = code >= 65 && code <= 90 ? 65 : code >= 97 && code <= 122 ? 97 : null;
  return base === null ? char : String.fromCharCode(base + ((code - base + amount % 26 + 26) % 26));
}
function caesar(text, shift, decrypt) {
  return Array.from(text, char => shiftLetter(char, decrypt ? -shift : shift)).join('');
}
function vigenere(text, keyword, decrypt) {
  let index = 0;
  return Array.from(text, char => {
    if (!/[A-Za-z]/.test(char)) return char;
    const shift = keyword.toUpperCase().charCodeAt(index++ % keyword.length) - 65;
    return shiftLetter(char, decrypt ? -shift : shift);
  }).join('');
}
const encoder = new TextEncoder();
const decoder = new TextDecoder('utf-8', { fatal: true });
function bytesToBase64(bytes) { return btoa(Array.from(bytes, b => String.fromCharCode(b)).join('')); }
function base64ToBytes(value) {
  const binary = atob(value);
  return Uint8Array.from(binary, c => c.charCodeAt(0));
}
async function aesKey(password, salt) {
  const material = await crypto.subtle.importKey('raw', encoder.encode(password), 'PBKDF2', false, ['deriveKey']);
  return crypto.subtle.deriveKey({ name: 'PBKDF2', salt, iterations: 100000, hash: 'SHA-256' }, material,
    { name: 'AES-GCM', length: 256 }, false, ['encrypt', 'decrypt']);
}
async function aesEncrypt(text, password) {
  const salt = crypto.getRandomValues(new Uint8Array(16));
  const iv = crypto.getRandomValues(new Uint8Array(12));
  const encrypted = new Uint8Array(await crypto.subtle.encrypt({ name: 'AES-GCM', iv }, await aesKey(password, salt), encoder.encode(text)));
  return `AES1:${bytesToBase64(salt)}:${bytesToBase64(iv)}:${bytesToBase64(encrypted)}`;
}
async function aesDecrypt(text, password) {
  const parts = text.trim().split(':');
  if (parts.length !== 4 || parts[0] !== 'AES1') throw new Error('Enter ciphertext generated by this AES option.');
  try {
    const salt = base64ToBytes(parts[1]); const iv = base64ToBytes(parts[2]); const data = base64ToBytes(parts[3]);
    if (salt.length !== 16 || iv.length !== 12 || data.length < 16) throw new Error('Invalid data');
    const plain = await crypto.subtle.decrypt({ name: 'AES-GCM', iv }, await aesKey(password, salt), data);
    return decoder.decode(plain);
  } catch { throw new Error('Decryption failed. Check the password and ciphertext.'); }
}
async function run(decrypt) {
  error.textContent = ''; status.textContent = ''; output.value = '';
  try {
    validate();
    if (method.value === 'caesar') output.value = caesar(input.value, Number(key.value), decrypt);
    if (method.value === 'vigenere') output.value = vigenere(input.value, key.value, decrypt);
    if (method.value === 'aes') {
      if (!crypto.subtle) throw new Error('AES needs a secure browser context. Open on localhost or HTTPS.');
      output.value = decrypt ? await aesDecrypt(input.value, key.value) : await aesEncrypt(input.value, key.value);
    }
  } catch (cause) { error.textContent = cause.message; }
}
document.querySelector('#encrypt').addEventListener('click', () => run(false));
document.querySelector('#decrypt').addEventListener('click', () => run(true));
document.querySelector('#copy').addEventListener('click', async () => {
  status.textContent = ''; error.textContent = '';
  if (!output.value) { error.textContent = 'There is no result to copy.'; return; }
  try { await navigator.clipboard.writeText(output.value); status.textContent = 'Result copied.'; }
  catch { error.textContent = 'Copy is unavailable here. Select and copy the result manually.'; }
});
